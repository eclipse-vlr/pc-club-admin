export function blockerHint(code: string): string {
  return Object.hasOwn(hints, code) ? hints[code] : '';
}

export function actionFeedback(cause: unknown, saved = false): ActionFeedback {
  if (saved) return {
    message: 'Действие сохранено, но обновлённое состояние не получено.',
    instruction: 'Перечитайте передачу. Повторно отправлять подтверждение не нужно.',
  };
  if (cause instanceof APIError) {
    const rejected = cause.status !== undefined && cause.status >= 400 && cause.status < 500;
    return {
      message: cause.message,
      instruction: rejected
        ? (blockerHint(cause.code) || 'Сервер отклонил запрос. Перечитайте данные и устраните причину перед новой попыткой.')
        : 'Результат действия неизвестен: оно могло сохраниться. Проверьте сессию и перечитайте передачу; до этого повтор недоступен.',
    };
  }
  return { message: cause instanceof Error ? cause.message : 'Проверьте введённые данные.', instruction: 'Исправьте ввод и перечитайте данные перед новой попыткой.' };
}
